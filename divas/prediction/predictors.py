"""Stage 4 -- interaction-aware trajectory prediction.

Two predictors live here and both matter:

``ConstantVelocityPredictor`` is the *baseline*.  It is what nearly every
published stack assumes, it is what the ablation in Phase 5 has to beat, and
it is deliberately overconfident -- a single mode reported at confidence 1.0,
because that is exactly the failure being argued against.

``SocialForcePredictor`` is the contribution.  It rolls agents forward under a
social-force model so a predicted two-wheeler bends around other traffic
instead of driving through it, and it emits *multiple weighted modes* whose
spread grows with the track's measured uncertainty.  That spread is what
:attr:`PredictedTrajectory.confidence` measures, and that confidence is what
widens the controller's safety margin.  The three are one mechanism.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import List, Optional, Sequence

import numpy as np

from divas.types import (
    CLASS_AGILITY,
    EgoState,
    OccupancyGrid,
    PredictedTrajectory,
    Track,
    TrajectoryMode,
    TrajectorySet,
)


class Predictor:
    """Interface for stage 4."""

    def predict(
        self,
        tracks: Sequence[Track],
        grid: Optional[OccupancyGrid] = None,
        ego: Optional[EgoState] = None,
    ) -> TrajectorySet:
        raise NotImplementedError


@dataclass
class ConstantVelocityPredictor(Predictor):
    """Straight-line extrapolation.  The baseline to beat."""

    horizon: float = 3.0
    dt: float = 0.1

    def predict(self, tracks, grid=None, ego=None) -> TrajectorySet:
        n = int(round(self.horizon / self.dt))
        steps = np.arange(1, n + 1) * self.dt
        out = []
        for tr in tracks:
            pts = tr.position[None, :] + steps[:, None] * tr.velocity[None, :]
            out.append(
                PredictedTrajectory(
                    track_id=tr.id,
                    modes=[TrajectoryMode(1.0, pts)],
                    radius=tr.radius,
                    cls=tr.cls,
                    half_length=tr.half_length,
                    half_width=tr.half_width,
                )
            )
        return TrajectorySet(out, dt=self.dt, horizon=self.horizon)


@dataclass
class SocialForcePredictor(Predictor):
    """Multi-modal interaction-aware prediction.

    Each mode is a forward rollout under three forces:

    * **drive** -- relax toward a desired velocity (the mode's intent),
    * **social** -- exponential repulsion from every other agent and from the
      ego, so agents do not predict themselves into each other,
    * **obstacle** -- repulsion from occupied space, sampled from the
      occupancy grid's distance field, so predictions stay on the drivable
      area without needing a lane model.

    Modes are generated by perturbing the intent heading.  The spread is
    scaled by the actor's class agility (a motorcycle can change its mind far
    faster than a bus) *and* by the track's own position uncertainty, so a
    distant, noisily-observed actor produces a flat, low-confidence mode
    distribution.
    """

    horizon: float = 3.0
    dt: float = 0.1
    n_modes: int = 3
    relaxation: float = 0.6          # s, velocity relaxation time
    # Both defaults are set from measurement, not intuition.  Open-loop
    # prediction error over the scenario suite, mean over a 3 s horizon
    # (scripts/tune_predictor.py, constant-velocity baseline 3.54 m):
    #
    #   obstacle_strength  0.0 -> 3.45 m      social_strength  0.0 -> 3.45 m
    #                      1.5 -> 4.41 m                       0.6 -> 3.46 m
    #                      6.0 -> 4.55 m                       2.1 -> 3.48 m
    #
    # The obstacle force was the single largest source of error in the whole
    # stack: it pushes predicted agents off the road boundary in ways the
    # actual agents do not move, and it cost ~1.1 m of accuracy -- enough to
    # make this predictor *worse than constant velocity* and, through the risk
    # field, to lose 11 points of closed-loop success rate.
    #
    # Losing it costs nothing operationally: a prediction that strays off the
    # drivable area creates a keep-out in a region the occupancy grid already
    # blocks, so the ego was never going there.
    #
    # The social term is kept small rather than removed.  It is neutral here
    # because the suite's actors are scripted and do not react to each other
    # (see docs/decisions/ADR-009), so this benchmark cannot reward
    # interaction-awareness at all.  Retuning it needs reactive actors first.
    social_strength: float = 0.6     # m/s^2
    social_range: float = 1.4        # m
    obstacle_strength: float = 0.0   # m/s^2 -- disabled; see above
    obstacle_range: float = 1.2      # m
    base_spread: float = 0.15        # rad, spread at zero measurement noise
    noise_gain: float = 0.30         # rad per metre of position sigma
    max_speed: float = 16.0

    # -- helpers ----------------------------------------------------------
    def _mode_offsets(self, spread: float) -> np.ndarray:
        if self.n_modes <= 1:
            return np.zeros(1)
        k = (self.n_modes - 1) // 2
        offs = np.arange(-k, k + 1, dtype=np.float64)
        if self.n_modes % 2 == 0:  # keep a centre mode even for even counts
            offs = np.arange(self.n_modes, dtype=np.float64) - (self.n_modes - 1) / 2
        return offs * spread

    def _obstacle_force(self, grid: Optional[OccupancyGrid], pos: np.ndarray) -> np.ndarray:
        """Gradient-ascent away from occupied cells, from the EDT."""
        if grid is None:
            return np.zeros_like(pos)
        eps = max(grid.resolution, 0.1)
        d = grid.signed_clearance_at(pos[:, 0], pos[:, 1], outside=-1.0)
        dx = (
            grid.signed_clearance_at(pos[:, 0] + eps, pos[:, 1], outside=-1.0)
            - grid.signed_clearance_at(pos[:, 0] - eps, pos[:, 1], outside=-1.0)
        ) / (2 * eps)
        dy = (
            grid.signed_clearance_at(pos[:, 0], pos[:, 1] + eps, outside=-1.0)
            - grid.signed_clearance_at(pos[:, 0], pos[:, 1] - eps, outside=-1.0)
        ) / (2 * eps)
        mag = self.obstacle_strength * np.exp(-d / self.obstacle_range)
        g = np.stack([dx, dy], axis=1)
        norm = np.linalg.norm(g, axis=1, keepdims=True)
        g = g / np.maximum(norm, 1e-6)
        return mag[:, None] * g

    # -- main -------------------------------------------------------------
    def predict(self, tracks, grid=None, ego=None) -> TrajectorySet:
        tracks = list(tracks)
        n_steps = int(round(self.horizon / self.dt))
        if not tracks:
            return TrajectorySet([], dt=self.dt, horizon=self.horizon)

        pos0 = np.array([t.position for t in tracks])
        vel0 = np.array([t.velocity for t in tracks])
        radii = np.array([t.radius for t in tracks])
        n_actors = len(tracks)

        # Per-actor mode spread: class agility x measurement uncertainty.
        spreads = np.array(
            [
                (self.base_spread + self.noise_gain * t.position_uncertainty)
                * CLASS_AGILITY.get(t.cls, 0.8)
                for t in tracks
            ]
        )

        # Ego rolled forward at constant velocity so agents can react to us.
        if ego is not None:
            ego_p0 = np.array([ego.x, ego.y])
            ego_v = np.array([ego.v * np.cos(ego.theta), ego.v * np.sin(ego.theta)])
        else:
            ego_p0 = None

        # Every actor's mode k is rolled out simultaneously, so the social
        # term sees a coherent scene rather than each actor reacting to the
        # others' *current* positions.
        offsets = self._mode_offsets(1.0)  # unit offsets, scaled per actor below
        all_modes: List[np.ndarray] = []
        for k, unit in enumerate(offsets):
            ang = unit * spreads
            c, s = np.cos(ang), np.sin(ang)
            v_des = np.stack(
                [c * vel0[:, 0] - s * vel0[:, 1], s * vel0[:, 0] + c * vel0[:, 1]],
                axis=1,
            )
            pos = pos0.copy()
            vel = vel0.copy()
            traj = np.empty((n_steps, n_actors, 2))
            for i in range(n_steps):
                f = (v_des - vel) / self.relaxation

                # pairwise repulsion between actors
                diff = pos[:, None, :] - pos[None, :, :]
                dist = np.linalg.norm(diff, axis=2)
                surface = dist - (radii[:, None] + radii[None, :])
                np.fill_diagonal(dist, np.inf)
                np.fill_diagonal(surface, np.inf)
                mag = self.social_strength * np.exp(-surface / self.social_range)
                unit_v = diff / np.maximum(dist, 1e-6)[:, :, None]
                f += (mag[:, :, None] * unit_v).sum(axis=1)

                # repulsion from the ego
                if ego_p0 is not None:
                    ep = ego_p0 + ego_v * (i + 1) * self.dt
                    d = pos - ep
                    dn = np.linalg.norm(d, axis=1)
                    surf = dn - radii - 1.0
                    m = self.social_strength * np.exp(-surf / self.social_range)
                    f += m[:, None] * d / np.maximum(dn, 1e-6)[:, None]

                f += self._obstacle_force(grid, pos)

                vel = vel + f * self.dt
                sp = np.linalg.norm(vel, axis=1, keepdims=True)
                # np.maximum guards a stationary actor (sp == 0, e.g. a
                # single-photo detection with no measured velocity): the
                # unused branch of np.where is still evaluated elementwise,
                # so 0/0 would warn even though the result is discarded.
                vel = np.where(sp > self.max_speed, vel / np.maximum(sp, 1e-9) * self.max_speed, vel)
                pos = pos + vel * self.dt
                traj[i] = pos
            all_modes.append(traj)

        # Mode weights: the unperturbed intent is most likely, and the
        # distribution flattens as spread grows -- which is precisely how an
        # uncertain track becomes a low-confidence, wide-margin one.
        out: List[PredictedTrajectory] = []
        for j, tr in enumerate(tracks):
            # Gaussian over the intent offset, on a fixed scale.  Weighting
            # by base_spread/spread instead made the outer modes carry over
            # half the probability mass whenever the track was noisy, so "the
            # actor might swerve 25 degrees" was treated as nearly as likely
            # as "it carries on", and the keep-out fanned across the road.
            w = np.exp(-0.5 * (offsets / 0.65) ** 2)
            w = w / w.sum()
            modes = [
                TrajectoryMode(float(w[k]), all_modes[k][:, j, :])
                for k in range(len(offsets))
            ]
            out.append(
                PredictedTrajectory(
                    track_id=tr.id,
                    modes=modes,
                    radius=tr.radius,
                    cls=tr.cls,
                    half_length=tr.half_length,
                    half_width=tr.half_width,
                )
            )
        return TrajectorySet(out, dt=self.dt, horizon=self.horizon)
